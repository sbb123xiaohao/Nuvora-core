#!/usr/bin/env python3
"""Embed the checked-in Java demo bytes; normal OS builds do not require a JDK."""
import pathlib
import struct
import sys

source, target = map(pathlib.Path, sys.argv[1:])
data = source.read_bytes()
if len(data) < 10 or struct.unpack('>IHH', data[:8]) != (0xcafebabe, 0, 65):
    raise SystemExit('Expected the non-preview Java 21 demo class')
lines = ['/* Generated by scripts/embed_java.py; do not edit. */',
         'static const u8 java_demo[] = {']
for at in range(0, len(data), 16):
    lines.append('    ' + ','.join(f'0x{byte:02x}' for byte in data[at:at+16]) + ',')
lines += ['};', '']
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('\n'.join(lines))
